-- =====================================================================
--  Sistema de Aluguel de Carros — Script do banco (Supabase / PostgreSQL)
--  Opcional: com SPRING_JPA_DDL_AUTO=update o Hibernate cria as tabelas
--  automaticamente. Use este script no SQL Editor do Supabase caso prefira
--  criar o schema manualmente (e então use SPRING_JPA_DDL_AUTO=validate).
-- =====================================================================

create table if not exists usuarios (
    id          bigint generated by default as identity primary key,
    login       varchar(60)  not null unique,
    senha_hash  varchar(255) not null,
    perfil      varchar(20)  not null check (perfil in ('CLIENTE', 'AGENTE')),
    criado_em   timestamp    not null default now()
);

create table if not exists clientes (
    usuario_id  bigint primary key references usuarios (id) on delete cascade,
    rg          varchar(20)  not null,
    cpf         varchar(14)  not null unique,
    nome        varchar(120) not null,
    endereco    varchar(255) not null,
    profissao   varchar(80)
);

create table if not exists agentes (
    usuario_id  bigint primary key references usuarios (id) on delete cascade,
    nome        varchar(120) not null,
    cnpj        varchar(18)  not null unique,
    tipo        varchar(20)  not null check (tipo in ('EMPRESA', 'BANCO'))
);

-- Rendimentos auferidos (máximo 3 por cliente — regra garantida pela aplicação)
create table if not exists rendimentos (
    id                    bigint generated by default as identity primary key,
    entidade_empregadora  varchar(120)   not null,
    valor                 numeric(12, 2) not null check (valor >= 0),
    cliente_id            bigint         not null references clientes (usuario_id) on delete cascade
);

create table if not exists automoveis (
    id                 bigint generated by default as identity primary key,
    matricula          varchar(30) not null unique,
    ano                integer     not null,
    marca              varchar(60) not null,
    modelo             varchar(60) not null,
    placa              varchar(10) not null unique,
    tipo_proprietario  varchar(20) check (tipo_proprietario in ('CLIENTE', 'EMPRESA', 'BANCO')),
    proprietario_id    bigint references usuarios (id),
    disponivel         boolean     not null default true
);

create table if not exists pedidos_aluguel (
    id                        bigint generated by default as identity primary key,
    cliente_id                bigint       not null references clientes (usuario_id),
    automovel_id              bigint       not null references automoveis (id),
    data_inicio               date         not null,
    data_fim                  date         not null,
    observacoes               varchar(500),
    solicita_credito          boolean      not null default false,
    valor_credito_solicitado  numeric(12, 2),
    status                    varchar(20)  not null default 'PENDENTE'
        check (status in ('PENDENTE', 'APROVADO', 'REPROVADO', 'CANCELADO', 'CONTRATADO')),
    agente_avaliador_id       bigint references agentes (usuario_id),
    parecer                   varchar(500),
    criado_em                 timestamp    not null default now(),
    atualizado_em             timestamp,
    constraint ck_periodo check (data_fim >= data_inicio)
);

create table if not exists contratos_credito (
    id                 bigint generated by default as identity primary key,
    banco_id           bigint         not null references agentes (usuario_id),
    valor              numeric(12, 2) not null check (valor > 0),
    taxa_juros_mensal  numeric(5, 2)  not null check (taxa_juros_mensal >= 0),
    numero_parcelas    integer        not null check (numero_parcelas between 1 and 120)
);

create table if not exists contratos (
    id                   bigint generated by default as identity primary key,
    pedido_id            bigint      not null unique references pedidos_aluguel (id),
    agente_id            bigint      not null references agentes (usuario_id),
    tipo_proprietario    varchar(20) not null check (tipo_proprietario in ('CLIENTE', 'EMPRESA', 'BANCO')),
    contrato_credito_id  bigint unique references contratos_credito (id),
    data_assinatura      timestamp   not null default now()
);

create index if not exists idx_pedidos_cliente on pedidos_aluguel (cliente_id);
create index if not exists idx_pedidos_status  on pedidos_aluguel (status);
